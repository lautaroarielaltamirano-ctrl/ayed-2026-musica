class Cancion:
    def __init__(self, id, titulo, artista, album, genero, anio, duracion_seg):
        self._id = id
        self._titulo = titulo
        self._artista = artista
        self._album = album
        self._genero = genero
        self._anio = anio
        self._duracion_seg = duracion_seg

    @property
    def id(self):
        return self._id

    @property
    def titulo(self):
        return self._titulo

    @property
    def artista(self):
        return self._artista

    @property
    def album(self):
        return self._album

    @property
    def genero(self):
        return self._genero

    @property
    def anio(self):
        return self._anio

    @property
    def duracion_seg(self):
        return self._duracion_seg

    def __repr__(self):
        minutos = self._duracion_seg // 60
        segundos = self._duracion_seg % 60
        return (
            f"{self._id:>2} | {self._titulo} | {self._artista} | "
            f"{self._genero} | {self._anio} | {minutos}:{segundos:02d}"
        )


class Catalogo:
    def __init__(self):
        self._canciones = []

    def cargar_datos(self, datos):
        for dato in datos:
            cancion = Cancion(
                dato["id"],
                dato["titulo"],
                dato["artista"],
                dato["album"],
                dato["genero"],
                dato["anio"],
                dato["duracion_seg"]
            )
            self._canciones.append(cancion)

    def listar(self):
        if not self._canciones:
            print("El catálogo está vacío.")
            return

        print("\n" + "=" * 90)
        print("CATÁLOGO DE MUSICFLOW")
        print("=" * 90)

        for cancion in self._canciones:
            print(cancion)

    def buscar_por_titulo(self, texto):
        resultados = []
        texto = texto.lower()

        for cancion in self._canciones:
            if texto in cancion.titulo.lower():
                resultados.append(cancion)

        return resultados

    def buscar_por_artista(self, texto):
        resultados = []
        texto = texto.lower()

        for cancion in self._canciones:
            if texto in cancion.artista.lower():
                resultados.append(cancion)

        return resultados

    def filtrar_por_genero(self, genero):
        resultados = []
        genero = genero.lower()

        for cancion in self._canciones:
            if cancion.genero.lower() == genero:
                resultados.append(cancion)

        return resultados

    def filtrar_por_anio(self, anio):
        resultados = []

        for cancion in self._canciones:
            if cancion.anio == anio:
                resultados.append(cancion)

        return resultados

    def mostrar_resultados(self, resultados):
        if not resultados:
            print("\nNo se encontraron canciones.")
            return

        print("\nResultados:")
        print("-" * 90)

        for cancion in resultados:
            print(cancion)

    def cantidad(self):
        return len(self._canciones)


