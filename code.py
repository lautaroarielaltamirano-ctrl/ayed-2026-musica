#  ÁRBOL BINARIO DE BÚSQUEDA

class NodoBST:
    def __init__(self, cancion):
        self.cancion = cancion
        self.izquierda = None
        self.derecha = None


class ArbolBST:
    def __init__(self):
        self.raiz = None

    def insertar(self, cancion):
        self.raiz = self._insertar(self.raiz, cancion)

    def _insertar(self, nodo, cancion):
        if nodo is None:
            return NodoBST(cancion)

        if cancion.titulo.lower() < nodo.cancion.titulo.lower():
            nodo.izquierda = self._insertar(nodo.izquierda, cancion)
        else:
            nodo.derecha = self._insertar(nodo.derecha, cancion)

        return nodo

    def buscar(self, titulo):
        nodo = self.raiz
        titulo = titulo.lower()

        while nodo:
            actual = nodo.cancion.titulo.lower()

            if titulo == actual:
                return nodo.cancion
            if titulo < actual:
                nodo = nodo.izquierda
            else:
                nodo = nodo.derecha

        return None

    def inorden(self):
        resultado = []

        def recorrer(nodo):
            if nodo:
                recorrer(nodo.izquierda)
                resultado.append(nodo.cancion)
                recorrer(nodo.derecha)

        recorrer(self.raiz)
        return resultado


# ÁRBOL AVL

class NodoAVL:
    def __init__(self, cancion):
        self.cancion = cancion
        self.izquierda = None
        self.derecha = None
        self.altura = 1


class ArbolAVL:
    def __init__(self):
        self.raiz = None

    def altura(self, nodo):
        return nodo.altura if nodo else 0

    def actualizar_altura(self, nodo):
        nodo.altura = 1 + max(
            self.altura(nodo.izquierda),
            self.altura(nodo.derecha)
        )

    def factor_balance(self, nodo):
        if nodo is None:
            return 0
        return self.altura(nodo.izquierda) - self.altura(nodo.derecha)

    def rotar_derecha(self, y):
        x = y.izquierda
        temporal = x.derecha

        x.derecha = y
        y.izquierda = temporal

        self.actualizar_altura(y)
        self.actualizar_altura(x)
        return x

    def rotar_izquierda(self, x):
        y = x.derecha
        temporal = y.izquierda

        y.izquierda = x
        x.derecha = temporal

        self.actualizar_altura(x)
        self.actualizar_altura(y)
        return y

    def insertar(self, cancion):
        self.raiz = self._insertar(self.raiz, cancion)

    def _insertar(self, nodo, cancion):
        if nodo is None:
            return NodoAVL(cancion)

        titulo = cancion.titulo.lower()
        actual = nodo.cancion.titulo.lower()

        if titulo < actual:
            nodo.izquierda = self._insertar(nodo.izquierda, cancion)
        else:
            nodo.derecha = self._insertar(nodo.derecha, cancion)

        self.actualizar_altura(nodo)
        balance = self.factor_balance(nodo)

        if balance > 1:
            if titulo < nodo.izquierda.cancion.titulo.lower():
                return self.rotar_derecha(nodo)

            nodo.izquierda = self.rotar_izquierda(nodo.izquierda)
            return self.rotar_derecha(nodo)

        if balance < -1:
            if titulo >= nodo.derecha.cancion.titulo.lower():
                return self.rotar_izquierda(nodo)

            nodo.derecha = self.rotar_derecha(nodo.derecha)
            return self.rotar_izquierda(nodo)

        return nodo

    def buscar(self, titulo):
        nodo = self.raiz
        titulo = titulo.lower()

        while nodo:
            actual = nodo.cancion.titulo.lower()

            if titulo == actual:
                return nodo.cancion
            if titulo < actual:
                nodo = nodo.izquierda
            else:
                nodo = nodo.derecha

        return None

    def inorden(self):
        resultado = []

        def recorrer(nodo):
            if nodo:
                recorrer(nodo.izquierda)
                resultado.append(nodo.cancion)
                recorrer(nodo.derecha)

        recorrer(self.raiz)
        return resultado

    def altura_arbol(self):return self.altura(self.raiz)


